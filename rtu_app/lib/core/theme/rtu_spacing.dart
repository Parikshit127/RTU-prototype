/// RTU Spacing System
/// ─────────────────────────────────────────────────────────────────
/// 4px base unit grid — consistent with Material 3 and RTU's
/// engineering-precision design language
/// ─────────────────────────────────────────────────────────────────
class RTUSpacing {
  RTUSpacing._();

  /// 2px — hairline gaps
  static const double xxs = 2.0;

  /// 4px — tight inner padding
  static const double xs = 4.0;

  /// 8px — compact spacing, icon gaps
  static const double sm = 8.0;

  /// 12px — between related elements
  static const double md = 12.0;

  /// 16px — standard padding, card padding
  static const double lg = 16.0;

  /// 20px — between sections within a card
  static const double xl = 20.0;

  /// 24px — between cards, major sections
  static const double xxl = 24.0;

  /// 32px — screen top/bottom padding
  static const double xxxl = 32.0;

  /// 48px — major section breaks
  static const double huge = 48.0;

  /// 64px — hero spacing, splash elements
  static const double massive = 64.0;

  // ── BORDER RADIUS ──
  /// 4px — subtle rounding (chips, tags)
  static const double radiusXs = 4.0;

  /// 8px — standard cards, buttons
  static const double radiusSm = 8.0;

  /// 12px — prominent cards, dialogs
  static const double radiusMd = 12.0;

  /// 16px — bottom sheets, large cards
  static const double radiusLg = 16.0;

  /// 24px — pill shapes, floating elements
  static const double radiusXl = 24.0;

  /// Full circle
  static const double radiusFull = 999.0;
}
